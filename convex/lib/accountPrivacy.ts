export function assertDeletionConfirmation(value: string) {
  if (value !== ACCOUNT_DELETION_CONFIRMATION) {
    throw new ConvexError(`Type ${ACCOUNT_DELETION_CONFIRMATION} to confirm deletion.`);
  }
}

export function redactItemForExport(
  item: Doc<"items">,
  role: HouseholdRole
) {
  const visibility = visibilityForHouseholdRole(role);

  return {
    id: item._id,
    moveId: item.moveId,
    name: item.name,
    description: item.description,
    room: item.room,
    destinationRoom: item.destinationRoom,
    category: item.category,
    subcategory: item.subcategory,
    disposition: item.disposition,
    status: item.status,
    quantity: item.quantity,
    condition: item.condition,
    valueCents: visibility.estimatedValue ? item.valueCents : undefined,
    replacementValueCents: visibility.purchaseValue
      ? item.replacementValueCents
      : undefined,
    serialNumber: visibility.serialNumber ? item.serialNumber : undefined,
    modelNumber: visibility.serialNumber ? item.modelNumber : undefined,
    estimatedWeightLb: item.estimatedWeightLb,
    actualWeightLb: item.actualWeightLb,
    estimatedVolumeCuFt: item.estimatedVolumeCuFt,
    fragility: item.fragility,
    hazardousFlag: item.hazardousFlag,
    highValue: item.highValue,
    requiresPersonalTransport: item.requiresPersonalTransport,
    planningDefaultKeys: item.planningDefaultKeys,
    needsReview: item.needsReview,
    reviewFlags: item.reviewFlags,
    privateNotes: visibility.privateNotes ? item.privateNotes : undefined,
    createdVia: item.createdVia,
    createdAt: item.createdAt,
    updatedAt: item.updatedAt,
    deletedAt: item.deletedAt,
  };
}

